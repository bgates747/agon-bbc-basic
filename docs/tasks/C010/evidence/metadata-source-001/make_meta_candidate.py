"""Shorten four compiler-private symbol prefixes without changing emitted code.

Only exact quoted prefix strings are substituted. The public @/# targets,
scope rules, table capacities, runtimes and symbol-address algorithm stay fixed.
"""
from pathlib import Path
import hashlib
import json
import shutil

TASK = Path(__file__).resolve().parent
source = TASK/'candidate-fit.bas'
digest = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
assert digest(source) == 'b8afbfdb51de803e7c8e670d4c00e434371e3f2d0af4ce354ce29f3580cdd875'
text = source.read_text()
mapping = {'$if':'$', '$var':'$V', '$bind':'$B', '$proc':'$P'}
changes = {}
for old,new in mapping.items():
    # "$" already denotes the public string suffix; it is not used as a
    # numeric compiler-symbol prefix. The capital prefixes are otherwise absent.
    if new == '$':
        assert '"$"+STR$(' not in text
    else:
        assert '"'+new+'"' not in text, new
    changes[old] = dict(replacement=new, occurrences=text.count('"'+old+'"'))
    assert changes[old]['occurrences'] > 0
    text = text.replace('"'+old+'"','"'+new+'"')
assert len(mapping.values()) == len(set(mapping.values()))
candidate = TASK/'candidate-meta.bas'
assert not candidate.exists()
candidate.write_text(text)
evidence = TASK/'evidence/metadata-source-001'
evidence.mkdir(parents=True,exist_ok=False)
shutil.copyfile(source,evidence/'prior-source.bas')
shutil.copyfile(candidate,evidence/'compiler.bas')
shutil.copyfile(__file__,evidence/'make_meta_candidate.py')
report = dict(prior_source_sha256=digest(source),source_sha256=digest(candidate),
    changes=changes,scope='Private symbol text only; no generated byte sequence or language limit change',
    qualification=False)
(evidence/'results.json').write_text(json.dumps(report,indent=2)+'\n')
(evidence/'manifest.json').write_text(json.dumps({p.name:digest(p)
    for p in sorted(evidence.iterdir()) if p.name!='manifest.json'},indent=2)+'\n')
print(json.dumps(report))
