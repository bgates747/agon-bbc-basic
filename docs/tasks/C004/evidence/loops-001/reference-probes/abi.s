    ld de,ctl_frames_end
    or a
    sbc hl,de
    jp nz,failed
    call preserved
    call ctl_init
    ld ix,limit
    ld iy,step
    ld hl,body
    ld de,variable
    ld b,4
    call ctl_for
    jp c,failed
    ld a,3
    call ctl_check
    jp c,failed
    ld a,(ctl_frames+9)
    cp 3
    jp nz,failed
    ld a,(ctl_frames+14)
    cp 1
    jp nz,failed
body:
    ld a,(iterations)
    inc a
    ld (iterations),a
    ld de,variable
    call ctl_next
    jp c,failed
    ld a,(iterations)
    cp 3
    jp nz,failed
    ld a,(variable)
    cp 4
    jp nz,failed
    ld a,3
    call ctl_check
    jp nc,failed
    cp 32
    jp nz,failed
    ld ix,0x123456
    ld iy,0xabcdef
    call preserved
    ld hl,0
    jr finish
failed:
    ld hl,1
finish:
    ld sp,(saved_sp)
    pop iy
    pop ix
    pop de
    pop bc
    pop af
    ret
preserved:
    push ix
    pop hl
    ld de,0x123456
    or a
    sbc hl,de
    jp nz,failed
    push iy
    pop hl
    ld de,0xabcdef
    or a
    sbc hl,de
    jp nz,failed
    ld hl,0
    add hl,sp
    ld de,(saved_sp)
    dec de
    dec de
    dec de
    or a
    sbc hl,de
    jp nz,failed
    ret
